"""Render a newspaper front page summing up world news of Monday 23 Nov 2026.

Standard library only at module level. Pillow is imported lazily inside the
render function so that, if it is missing, main() falls back to copying the
shipped entry.png (generated by this same program) to the output path.

Layout concept (picked over two alternatives): classic broadsheet — masthead,
lead story with illustration, 2x2 story grid, bottom strip, footer. The two
rejected concepts were a globe-centred radial layout (text too cramped at
300 px) and a vertical timeline (weak hierarchy, lead story not prominent).
"""

import os
import shutil
import sys

W, H = 1024, 1024
WALLET = "EnAjSa7JsWs58b4M1zKy9bBCaeCzYuN1iHqgzdDWfEHf"


def _output_path():
    d = os.environ.get("MAKEFUN_OUTPUT_DIR")
    if d:
        return os.path.join(d, "entry.png")
    if os.path.isdir("/output"):
        return "/output/entry.png"
    return os.path.join(os.getcwd(), "entry.png")


def _render():
    """Draw the front page with Pillow. All Pillow names live in here only."""
    from PIL import Image, ImageDraw, ImageFont

    paper = (248, 244, 232)
    ink = (17, 17, 17)
    red = (178, 34, 34)
    blue = (31, 78, 121)
    grey = (90, 86, 76)
    light = (233, 227, 210)

    img = Image.new("RGB", (W, H), paper)
    dr = ImageDraw.Draw(img)

    def load_font(paths, size):
        for p in paths:
            try:
                return ImageFont.truetype(p, size), size
            except Exception:
                continue
        try:
            return ImageFont.load_default(size=size), size
        except TypeError:
            return ImageFont.load_default(), 13

    serif_b = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf",
        "/usr/share/fonts/dejavu/DejaVuSerif-Bold.ttf",
    ]
    serif = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf",
        "/usr/share/fonts/dejavu/DejaVuSerif.ttf",
    ]
    sans_b = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        "/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf",
    ]
    sans = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/dejavu/DejaVuSans.ttf",
    ]

    f_mast = load_font(serif_b, 62)
    f_date = load_font(sans_b, 21)
    f_kick = load_font(sans_b, 19)
    f_lead = load_font(serif_b, 44)
    f_deck = load_font(sans, 21)
    f_head = load_font(serif_b, 27)
    f_body = load_font(sans, 17)
    f_src = load_font(sans, 13)
    f_stamp = load_font(sans_b, 34)
    f_foot = load_font(sans, 14)

    def tw(font, text):
        f, size = font
        try:
            return f.getlength(text)
        except Exception:
            return len(text) * size * 0.55

    def text(font, x, y, s, fill=ink, anchor_left=True):
        f, _ = font
        if anchor_left:
            dr.text((x, y), s, font=f, fill=fill)
        else:
            dr.text((x, y), s, font=f, fill=fill, anchor="ma")

    def centre(font, cx, y, s, fill=ink):
        f, _ = font
        dr.text((cx, y), s, font=f, fill=fill, anchor="ma")

    def wrap(font, s, maxw):
        words = s.split(" ")
        lines, cur = [], ""
        for wd in words:
            trial = (cur + " " + wd).strip()
            if tw(font, trial) <= maxw or not cur:
                cur = trial
            else:
                lines.append(cur)
                cur = wd
        if cur:
            lines.append(cur)
        return lines

    def rule(y, weight=2, x0=30, x1=994, fill=ink):
        dr.line([(x0, y), (x1, y)], fill=fill, width=weight)

    def para(font, x, y, s, maxw, lh):
        for ln in wrap(font, s, maxw):
            text(font, x, y, ln)
            y += lh
        return y

    # ---------- masthead ----------
    centre(f_mast, 512, 18, "THE WORLD IN ONE DAY")
    rule(96, 3)
    centre(f_date, 512, 106, "MONDAY 23 NOVEMBER 2026  |  SIX STORIES FROM AROUND THE GLOBE")
    rule(138, 2)

    # ---------- lead story: COP31 collapse ----------
    text(f_kick, 30, 156, "CLIMATE  -  ANTALYA, TURKIYE", fill=red)
    y = 184
    for ln in ["CLIMATE TALKS", "COLLAPSE"]:
        text(f_lead, 30, y, ln)
        y += 48
    y = para(
        f_deck, 30, y + 8,
        "COP31 ends with no deal after record overtime: nearly 200 nations "
        "fail to agree, as a draft with no fossil-fuel phase-out is rejected.",
        560, 27)
    y = para(
        f_body, 30, y + 10,
        "The longest climate summit on record breaks down in chaos. The UN "
        "chief says he is 'deeply disappointed'.",
        560, 22)
    text(f_src, 30, y + 8, "SOURCES: AFP, CNN, REUTERS  -  23 NOV 2026", fill=grey)

    # lead illustration: hot sun, globe cracked down the middle, NO DEAL stamp
    import math as _math
    px0, py0, px1, py1 = 622, 152, 994, 428
    dr.rectangle([px0, py0, px1, py1], outline=ink, width=2, fill=(214, 232, 240))
    sun_cx, sun_cy, sun_r = px1 - 86, py0 + 64, 40
    dr.ellipse([sun_cx - sun_r, sun_cy - sun_r, sun_cx + sun_r, sun_cy + sun_r],
               fill=(240, 178, 60), outline=ink, width=2)
    for k in range(8):
        ang = k * _math.pi / 4
        x_a = sun_cx + int((sun_r + 6) * _math.cos(ang))
        y_a = sun_cy + int((sun_r + 6) * _math.sin(ang))
        x_b = sun_cx + int((sun_r + 20) * _math.cos(ang))
        y_b = sun_cy + int((sun_r + 20) * _math.sin(ang))
        dr.line([(x_a, y_a), (x_b, y_b)], fill=(240, 178, 60), width=4)
    # globe, cracked
    cx, cy, r = 770, 288, 88
    dr.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(126, 180, 214), outline=ink, width=3)
    dr.ellipse([cx - 62, cy - 58, cx + 8, cy + 6], fill=(96, 160, 96))       # land mass 1
    dr.ellipse([cx - 6, cy + 8, cx + 62, cy + 62], fill=(96, 160, 96))       # land mass 2
    dr.ellipse([cx + 18, cy - 66, cx + 66, cy - 18], fill=(120, 172, 100))   # land mass 3
    dr.arc([cx - r, cy - r, cx + r, cy + r], 200, 340, fill=ink, width=2)
    # jagged red crack down the middle of the globe
    crack = [(cx - 6, cy - r + 4), (cx + 8, cy - 52), (cx - 10, cy - 18),
             (cx + 10, cy + 16), (cx - 8, cy + 50), (cx + 4, cy + r - 4)]
    dr.line(crack, fill=red, width=5, joint="curve")
    # NO DEAL stamp (drawn flat, red, boxed)
    dr.rectangle([px0 + 16, py1 - 66, px0 + 236, py1 - 18], outline=red, width=4)
    centre(f_stamp, px0 + 126, py1 - 62, "NO DEAL", fill=red)

    rule(446, 3)

    # ---------- 2x2 grid ----------
    cells = [
        # (x, y, kicker, headline lines, deck, sources, art)
        (30, 464, "WAR IN UKRAINE  -  DYMER", ["DRONE FLATTENS", "KYIV FLATS"],
         "A Russian drone destroys part of a five-storey block north of Kyiv. "
         "Five are killed, about nine feared in the rubble; the region "
         "declares a day of mourning.",
         "SOURCES: AP, REUTERS", "flats"),
        (527, 464, "GULF OF FINLAND", ["SHIP AFIRE AFTER", "DRONE ATTACK"],
         "The Russian cargo ship Sparta II, under US sanctions, catches fire "
         "after a drone strike and drifts into Finnish waters.",
         "SOURCES: AP, REUTERS", "ship"),
        (30, 656, "INDONESIA  -  SERANG", ["FACTORY FIRE:", "36 MISSING"],
         "A blaze at a candy factory kills three workers. Rescuers search the "
         "ruins for dozens still unaccounted for.",
         "SOURCES: AP, REUTERS", "fire"),
        (527, 656, "SOUTH KOREA  -  SEOUL", ["MINISTER QUITS", "IN AI CHEAT ROW"],
         "The education minister resigns over an AI-assisted cheating scandal "
         "days before the Suneung college entrance exam.",
         "SOURCES: AP, AFP", "exam"),
    ]

    def art_flats(x0, y0, x1, y1):
        dr.rectangle([x0, y0, x1, y1], fill=(226, 220, 205), outline=ink, width=2)
        dr.rectangle([x0 + 26, y0 + 18, x0 + 96, y1 - 10], fill=(150, 140, 120), outline=ink, width=2)
        dr.rectangle([x0 + 96, y0 + 34, x0 + 150, y1 - 10], fill=(120, 112, 96), outline=ink, width=2)
        for wy in (y0 + 30, y0 + 52):
            for wx in (x0 + 36, x0 + 60):
                dr.rectangle([wx, wy, wx + 12, wy + 12], fill=(240, 230, 180), outline=ink)
        dr.polygon([(x0 + 96, y0 + 34), (x0 + 128, y0 + 18), (x0 + 150, y0 + 34)],
                   fill=(90, 84, 72))
        dr.line([(x0 + 96, y0 + 34), (x0 + 110, y0 + 60), (x0 + 96, y0 + 78)], fill=ink, width=3)
        dr.ellipse([x0 + 118, y0 + 10, x0 + 158, y0 + 34], fill=(200, 200, 200), outline=grey)

    def art_ship(x0, y0, x1, y1):
        dr.rectangle([x0, y0, x1, y1], fill=(178, 205, 224), outline=ink, width=2)
        # hull and superstructure
        dr.polygon([(x0 + 18, y1 - 30), (x0 + 148, y1 - 30), (x0 + 136, y1 - 12),
                    (x0 + 30, y1 - 12)], fill=(40, 60, 80), outline=ink)
        dr.rectangle([x0 + 58, y1 - 56, x0 + 108, y1 - 30], fill=(220, 220, 220), outline=ink, width=2)
        dr.rectangle([x0 + 76, y1 - 70, x0 + 90, y1 - 56], fill=(120, 120, 120), outline=ink)
        # flames and smoke from the deck
        dr.polygon([(x0 + 116, y1 - 30), (x0 + 132, y1 - 62), (x0 + 118, y1 - 44),
                    (x0 + 128, y1 - 70), (x0 + 108, y1 - 46)],
                   fill=(240, 120, 40), outline=red)
        dr.ellipse([x0 + 122, y0 + 8, x0 + 152, y0 + 30], fill=(210, 210, 210), outline=grey)
        dr.ellipse([x0 + 132, y0 + 2, x0 + 158, y0 + 20], fill=(225, 225, 225), outline=grey)
        # waves
        dr.line([(x0 + 8, y1 - 6), (x1 - 8, y1 - 6)], fill=(255, 255, 255), width=2)

    def art_fire(x0, y0, x1, y1):
        dr.rectangle([x0, y0, x1, y1], fill=(238, 226, 210), outline=ink, width=2)
        dr.rectangle([x0 + 26, y0 + 40, x0 + 138, y1 - 10], fill=(170, 150, 130), outline=ink, width=2)
        dr.polygon([(x0 + 20, y0 + 40), (x0 + 144, y0 + 40), (x0 + 132, y0 + 26), (x0 + 32, y0 + 26)],
                   fill=(120, 104, 88), outline=ink)
        dr.rectangle([x0 + 60, y0 + 8, x0 + 76, y0 + 28], fill=(120, 104, 88), outline=ink)
        dr.polygon([(x0 + 68, y0 + 6), (x0 + 84, y0 + 34), (x0 + 62, y0 + 44), (x0 + 74, y0 + 22)],
                   fill=(240, 120, 40), outline=red)
        dr.ellipse([x0 + 108, y0 + 10, x0 + 150, y0 + 30], fill=(210, 210, 210), outline=grey)

    def art_exam(x0, y0, x1, y1):
        dr.rectangle([x0, y0, x1, y1], fill=(238, 236, 228), outline=ink, width=2)
        # test paper
        dr.rectangle([x0 + 30, y0 + 8, x0 + 120, y1 - 8], fill=(255, 255, 255), outline=ink, width=2)
        for i, ly in enumerate((y0 + 22, y0 + 36, y0 + 50)):
            dr.line([(x0 + 42, ly), (x0 + 108, ly)], fill=grey, width=2)
        # red X over the paper and a small chip
        dr.line([(x0 + 44, y0 + 18), (x0 + 104, y0 + 74)], fill=red, width=4)
        dr.line([(x0 + 104, y0 + 18), (x0 + 44, y0 + 74)], fill=red, width=4)
        dr.rectangle([x0 + 128, y0 + 52, x0 + 156, y1 - 14], fill=(40, 60, 80), outline=ink, width=2)
        dr.rectangle([x0 + 136, y0 + 60, x0 + 148, y0 + 72], fill=(120, 180, 220), outline=ink)

    arts = {"flats": art_flats, "ship": art_ship, "fire": art_fire, "exam": art_exam}

    for (cx0, cy0, kick, heads, deck, src, art) in cells:
        text(f_kick, cx0, cy0, kick, fill=red)
        hy = cy0 + 24
        for ln in heads:
            text(f_head, cx0, hy, ln)
            hy += 31
        arts[art](cx0 + 300, cy0 + 2, cx0 + 467, cy0 + 92)
        by = para(f_body, cx0, hy + 6, deck, 467, 22)
        text(f_src, cx0, by + 8, src, fill=grey)
        if cx0 == 30:
            dr.line([(512, cy0 - 6), (512, cy0 + 176)], fill=light, width=2)

    rule(846, 2)

    # ---------- bottom strip: tech ----------
    text(f_kick, 30, 862, "TECH  -  WASHINGTON", fill=red)
    text(f_head, 30, 888, "TRUMP BACKS HUANG REHIRE")
    text(f_body, 30, 926,
         "Trump urges Nvidia to rehire ex-CEO Jensen Huang amid a US spy probe tied to him.",
         fill=ink)
    text(f_src, 30, 954, "SOURCES: NYT, REUTERS  -  23 NOV 2026", fill=grey)
    # computer chip
    fx0, fy0, fx1, fy1 = 800, 862, 994, 972
    dr.rectangle([fx0, fy0, fx1, fy1], outline=ink, width=2, fill=(255, 255, 255))
    dr.rectangle([fx0 + 62, fy0 + 26, fx0 + 132, fy0 + 84], fill=(40, 60, 80), outline=ink, width=2)
    dr.rectangle([fx0 + 82, fy0 + 44, fx0 + 112, fy0 + 66], fill=(120, 180, 220), outline=ink)
    for px in (fx0 + 76, fx0 + 96, fx0 + 116):
        dr.line([(px, fy0 + 2), (px, fy0 + 26)], fill=ink, width=3)
        dr.line([(px, fy0 + 84), (px, fy0 + 108)], fill=ink, width=3)
    for py in (fy0 + 40, fy0 + 58, fy0 + 76):
        dr.line([(fx0 + 2, py), (fx0 + 62, py)], fill=ink, width=3)
        dr.line([(fx0 + 132, py), (fx0 + 192, py)], fill=ink, width=3)

    rule(988, 2)
    text(f_foot, 30, 996,
         "ALSO: KIM SAYS NORTH KOREA SEEKS SECURITY, NOT SUPREMACY  -  TRUMP WARNS IRAN  -  NEPAL PM IN DELHI",
         fill=grey)

    return img


def main():
    out = _output_path()
    try:
        os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
        img = _render()
        img.save(out, "PNG")
    except Exception:
        try:
            here = os.path.dirname(os.path.abspath(__file__))
            src = os.path.join(here, "entry.png")
            os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
            shutil.copyfile(src, out)
        except Exception:
            pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
